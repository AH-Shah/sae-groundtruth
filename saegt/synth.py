def log1p(C):
    return np.log1p(C / np.maximum(C.sum(1, keepdims=True), 1) * 1e4).astype(np.float32)


def prep(X, mode="unit"):
    X = X - X.mean(0)
    if mode == "unit": X = X / np.maximum(np.linalg.norm(X, axis=1, keepdims=True), 1e-9)
    if mode == "white": X = X / np.maximum(X.std(0), 1e-9)
    return (X / np.sqrt((X ** 2).mean())).astype(np.float32)


def score(Z, U, kind, lin_of, lin, thr=.7):
    """per program best activation corr; states within their lineage; identity/shared over all cells."""
    Zs = (Z - Z.mean(0)) / np.maximum(Z.std(0), 1e-9); best = np.zeros(U.shape[1])

    def bc(m, j):
        u = U[m, j]
        if u.std() == 0: return 0.0
        Zm = Z[m]; Zm = (Zm - Zm.mean(0)) / np.maximum(Zm.std(0), 1e-9); return float(np.nanmax((Zm.T @ ((u - u.mean()) / u.std())) / m.sum()))
    for j in range(U.shape[1]):
        if kind[j].startswith("state"): best[j] = bc(lin == lin_of[j], j)
        elif kind[j] == "shared": best[j] = np.mean([bc(lin == l, j) for l in range(NL)])  # within each lineage (fair to per-lineage fits)
        else: best[j] = bc(np.ones(len(U), bool), j)
    K = ("identity", "state_hi", "state_mid", "state_lo", "shared")
    out = {f"rec_{k}": float((best[kind == k] >= thr).mean()) for k in K}; out.update({f"r_{k}": float(np.median(best[kind == k])) for k in K})
    # duplicates and composites: features matching an identity indicator at r >= .7; within that lineage, their best state corr
    C_id = (Zs.T @ ((U[:, :NL] - U[:, :NL].mean(0)) / U[:, :NL].std(0))) / len(U); dup, comp = [], []
    for l in range(NL):
        fs = np.flatnonzero(C_id[:, l] >= .7); dup.append(len(fs)); m = lin == l
        for f in fs:
            z = Z[m, f]
            if z.std() == 0: comp.append(0.0); continue
            us = U[m][:, [j for j in range(U.shape[1]) if kind[j].startswith("state") and lin_of[j] == l]]
            comp.append(float(np.max([np.corrcoef(z, us[:, i])[0, 1] for i in range(us.shape[1])])))
    out.update(id_dup=float(np.mean(dup)), composite_share=float(np.mean(np.array(comp) >= .5)) if comp else 0.0, n_feat=int((Z != 0).any(0).sum()))
    return out


def mono_share(Z, U, thr=.7):
    """ground-truth monosemanticity: share of alive features whose activation correlates >= thr with one planted program (all cells)."""
    from saegt import sae as dense
    Za = Z[:, dense.alive(Z)]
    if Za.shape[1] == 0: return 0.0
    Zs = (Za - Za.mean(0)) / np.maximum(Za.std(0), 1e-9); Us = (U - U.mean(0)) / np.maximum(U.std(0), 1e-9)
    return float(((Zs.T @ Us / len(U)).max(1) >= thr).mean())


