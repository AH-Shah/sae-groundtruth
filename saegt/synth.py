import numpy as np

NL, NS, NH, G = 6, 3, 4, 1000
PROP = np.array([0.35, 0.25, 0.15, 0.1, 0.1, 0.05])


def simulate(n=20000, depth=150, seed=0):
    """rates = baseline (patient-shifted) + identity + active states (within lineage) + active shared programs; Poisson counts."""
    rng = np.random.default_rng(seed); genes = rng.permutation(G)
    base = rng.lognormal(0, 1, G); base /= base.sum()
    idg = [genes[50 * l:50 * (l + 1)] for l in range(NL)]; rest = genes[50 * NL:]
    progs, kind, lin_of = [], [], []
    for l in range(NL):
        v = np.zeros(G); v[idg[l]] = rng.lognormal(0, .5, 50); progs.append(v / v.sum()); kind.append("identity"); lin_of.append(l)
    for l in range(NL):
        for s in range(NS):
            v = np.zeros(G); v[rng.choice(rest, 30, replace=False)] = rng.lognormal(0, .5, 30); progs.append(v / v.sum()); kind.append("state"); lin_of.append(l)
    for h in range(NH):
        v = np.zeros(G); v[rng.choice(rest, 30, replace=False)] = rng.lognormal(0, .5, 30); progs.append(v / v.sum()); kind.append("shared"); lin_of.append(-1)
    P = np.array(progs); lin = rng.choice(NL, n, p=PROP); pat = rng.integers(0, 4, n)
    pshift = rng.lognormal(0, .25, (4, G)); U = np.zeros((n, len(P)), np.float32)
    for l in range(NL): U[lin == l, l] = 1.0
    for j in range(NL, NL + NL * NS):
        l = lin_of[j]; act = (lin == l) & (rng.random(n) < .35); U[act, j] = rng.gamma(2, .5, act.sum())
    for j in range(NL + NL * NS, len(P)):
        act = rng.random(n) < .15; U[act, j] = rng.gamma(2, .5, act.sum())
    # mixture weights: baseline .45, identity .35; states .12 / .06 / .03 x usage (strong / mid / weak), shared .06 x usage
    wt = np.array([.35] * NL + [.12, .06, .03] * NL + [.06] * NH); W = U * wt[None]
    R = .45 * base[None] * pshift[pat] / (base[None] * pshift[pat]).sum(1, keepdims=True) + W @ P
    R /= R.sum(1, keepdims=True); lib = rng.lognormal(np.log(depth), .4, n)
    C = rng.poisson(R * lib[:, None]).astype(np.float32)
    kind = np.array(kind, dtype="<U12"); kind[NL:NL + NL * NS] = np.array(["state_hi", "state_mid", "state_lo"] * NL)
